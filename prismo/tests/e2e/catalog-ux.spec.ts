import { expect, test } from '@playwright/test'

test('catálogo muestra temas, indicadores, fuentes y próximas categorías', async ({ page }) => {
  await page.goto('/explorar')
  await expect(page.getByRole('heading', { name: 'Economía y finanzas' })).toBeVisible()
  const inflation = page.locator('.catalog-section').filter({ hasText: 'Inflación al consumidor' })
  await expect(inflation.getByText('Fuente: Banco Mundial · FP.CPI.TOTL.ZG')).toBeVisible()
  await expect(inflation.getByRole('link', { name: /Inflación al consumidor/ })).toHaveAttribute('href', '/explorar/inflacion')
  await expect(page.locator('.catalog-section.is-coming')).toHaveCount(3)
  await expect(page.locator('.catalog-section.is-coming').first()).toContainText('Próximamente')
  await expect(page.locator('main')).not.toContainText(/CAT-\d+/)
  await expect(page.locator('main')).not.toContainText('Sección')
  await expect(page.locator('main > section > .eyebrow')).toHaveCount(0)
  const card = inflation.locator('.indicator-card')
  const initial = await card.evaluate(element => getComputedStyle(element).transform)
  await card.hover()
  await page.waitForTimeout(300)
  const hovered = await card.evaluate(element => getComputedStyle(element).transform)
  expect(hovered).not.toBe(initial)
  await expect(inflation).toHaveClass(/holo-card/)
  const tile = await inflation.evaluate(element => getComputedStyle(element).transform)
  expect(tile).not.toBe('none')
  const coming = page.locator('.catalog-section.is-coming').first()
  await expect(coming).toHaveAttribute('data-static', 'true')
  await coming.hover()
  await expect(coming).toHaveCSS('transform', 'none')
})

test('filtra el catálogo por indicador y disponibilidad', async ({ page }) => {
  await page.goto('/explorar')
  await page.getByRole('searchbox', { name: 'Buscar en el catálogo' }).fill('alfabetizacion')
  await expect(page.locator('.catalog-section')).toHaveCount(1)
  await expect(page.locator('.catalog-section')).toContainText('Educación')
  await page.getByRole('button', { name: 'Borrar búsqueda' }).click()
  await page.getByRole('button', { name: 'Próximamente' }).click()
  await expect(page.locator('.catalog-section.is-coming')).toHaveCount(3)
  await expect(page.locator('.indicator-card')).toHaveCount(0)
  await page.getByRole('button', { name: 'Disponibles' }).click()
  await expect(page.locator('.catalog-section')).toHaveCount(7)
})
